#!/usr/bin/env python3
"""
to_mdc.py — convert Agent Skills (SKILL.md) into Cursor rule files (.mdc).

Cursor's native rule format is `.mdc` with frontmatter fields:
    description   — when Cursor should attach the rule
    globs         — file patterns that auto-attach the rule (optional)
    alwaysApply   — bool; if true the rule is always in context (optional)

This converter reads every skills/<name>/SKILL.md and emits one .mdc file under
./.cursor/rules/ (or a directory you specify). The `description` is copied from
the skill's frontmatter so Cursor's model decides when to activate it.

Usage
-----
    python scripts/to_mdc.py                         # -> ./.cursor/rules/
    python scripts/to_mdc.py --out ~/.cursor/rules   # user-level rules
    python scripts/to_mdc.py --skill genomics       # convert just one
    python scripts/to_mdc.py --always               # mark all rules alwaysApply

The output is plain text; you can review and commit it alongside the repo.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SKILLS_DIR = REPO_ROOT / "skills"


def parse_frontmatter(text: str) -> tuple[dict, str]:
    if not text.startswith("---"):
        return {}, text
    lines = text.splitlines()
    close = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if close is None:
        return {}, text
    fm = "\n".join(lines[1:close])
    body = "\n".join(lines[close + 1 :])
    try:
        import yaml  # type: ignore

        return yaml.safe_load(fm) or {}, body
    except Exception:
        out: dict = {}
        for line in fm.splitlines():
            m = re.match(r"([\w-]+):\s*(.*)$", line)
            if m and m.group(2):
                out[m.group(1)] = m.group(2).strip().strip("\"'")
        return out, body


def convert_one(skill_md: Path, out_dir: Path, always: bool = False) -> Path:
    meta, body = parse_frontmatter(skill_md.read_text(encoding="utf-8"))
    name = meta.get("name", skill_md.parent.name)
    desc = meta.get("description", "")

    lines = ["---"]
    lines.append(f"description: {json_escape(desc)}")
    if always:
        lines.append("alwaysApply: true")
    lines.append("---")
    lines.append("")
    # preserve the body, but add a banner so readers know it's generated
    lines.append(f"<!-- Generated from skills/{name}/SKILL.md by scripts/to_mdc.py -->")
    lines.append(f"<!-- Do not edit this file directly; edit the source skill. -->")
    lines.append("")
    lines.append(body.rstrip())
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / f"{name}.mdc"
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out_path


def json_escape(s: str) -> str:
    # mdc descriptions are plain scalars; just escape quotes/newlines
    return s.replace('"', '\\"').replace("\n", " ")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="to_mdc.py", description=__doc__)
    p.add_argument("--out", default=".cursor/rules", help="output directory")
    p.add_argument("--skill", help="convert a single skill")
    p.add_argument("--always", action="store_true", help="set alwaysApply: true")
    args = p.parse_args(argv)

    out_dir = Path(args.out).expanduser()
    if args.skill:
        targets = [SKILLS_DIR / args.skill / "SKILL.md"]
    else:
        targets = sorted(SKILLS_DIR.glob("*/SKILL.md"))

    if not targets or not all(t.is_file() for t in targets):
        print("no SKILL.md files found")
        return 1

    print(f"Converting {len(targets)} skill(s) -> {out_dir}\n")
    for t in targets:
        out = convert_one(t, out_dir, always=args.always)
        print(f"  ✓ {t.parent.name:24s} -> {out}")
    print("\nRestart Cursor to load the new rules.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
